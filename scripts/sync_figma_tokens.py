#!/usr/bin/env python3
"""Synchronize checked-in Figma color tokens into the native and QML themes."""
from __future__ import annotations

import argparse
import json
from pathlib import Path
import re
import sys

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "resources/figma-color-tokens.json"
NATIVE = ROOT / "src/Styling/FigmaColors.h"
QML = ROOT / "src/qml/Theme.qml"
NOISE = ROOT / "src/backend/graphics/windownoisetexture.h"
COLORS = ("Blue", "Red", "Green", "Yellow", "Purple", "Rose", "Orange", "Brown", "Cyan", "Teal")
ROLES = ("Default", "Hover", "Pressed", "Selected", "Disabled", "Subtle", "Outline", "Overlay", "Text")
BACKGROUNDS = (
    ("Panel/canvas", "canvas"), ("Panel/surfaceGhost", "surfaceGhost"),
    ("Panel/windowAlt", "windowAlt"), ("Panel/subSurface", "subSurface"),
    ("Panel/surfaceSolid", "surfaceSolid"), ("Panel/surfaceAlt", "surfaceAlt"),
    ("Panel/surfaceInteractive", "surfaceInteractive"), ("Panel/surfacePanel", "surfacePanel"),
    ("Panel/surfaceControl", "surfaceControl"), ("Panel/surfaceInput", "surfaceInput"),
    ("Panel/surfaceInputHover", "surfaceInputHover"), ("Panel/surfaceRaised", "surfaceRaised"),
    ("Glass/Fill", None), ("TextField/Fill", None), ("TextField/Disabled", None),
    ("TextField/Inline", None), ("Surface/Dense/Fill", None), ("Surface/Glass/Fill", None),
    ("Backdrop/Base", None), ("Panel/window", "window"), ("Alert/canvas", None),
    ("Alert/surface", None),
)


def load_tokens():
    data = json.loads(SOURCE.read_text())
    rows = data["variables"]
    tokens = {row["name"]: row["value"] for row in rows}
    ids = [row["id"] for row in rows]
    if len(tokens) != len(rows) or len(set(ids)) != len(ids):
        raise ValueError("Duplicate Figma color token")
    expected = {f"Accent/{color}/{role}" for color in COLORS for role in ROLES}
    expected.update(name for name, _ in BACKGROUNDS)
    expected.update(row["name"] for row in rows if row["name"].startswith("Icon/Accent/"))
    if len(rows) != 141 or len([n for n in expected if n.startswith("Icon/Accent/")]) != 29 or set(tokens) != expected:
        raise ValueError("Incomplete or unexpected Figma color token inventory")
    for name, value in tokens.items():
        if set(value) != {"r", "g", "b", "a"} or any(not 0 <= value[k] <= 1 for k in value):
            raise ValueError(f"Invalid color channels: {name}")
    return tokens


def values(c):
    return ", ".join(repr(c[k]) for k in ("r", "g", "b", "a"))


def native_header(tokens):
    lines = ["// Generated by scripts/sync_figma_tokens.py from resources/figma-color-tokens.json.",
             "#pragma once", "#include <array>", "#include <iiGUI/Appearance.h>", "",
             "namespace lvrs::figma_colors {", "using Color = ii::gui::WidgetColor;",
             "inline constexpr std::array<std::array<Color, 9>, 10> accents{{"]
    for color in COLORS:
        lines.append("    std::array<Color, 9>{{")
        lines.extend(f"        Color{{{values(tokens[f'Accent/{color}/{role}'])}}}," for role in ROLES)
        lines.append("    }},")
    lines.extend(["}};", "inline constexpr std::array<Color, 22> backgrounds{{"])
    lines.extend(f"    Color{{{values(tokens[name])}}}, // {name}" for name, _ in BACKGROUNDS)
    icon_names = sorted(name for name in tokens if name.startswith("Icon/Accent/"))
    lines.extend(["}};", "struct IconAccent { std::size_t color; std::size_t role; Color value; };",
                  f"inline constexpr std::array<IconAccent, {len(icon_names)}> icon_accents{{{{"])
    for name in icon_names:
        _, _, color, role, _ = name.split("/")
        lines.append(f"    IconAccent{{{COLORS.index(color)}, {ROLES.index(role)}, Color{{{values(tokens[name])}}}}}, // {name}")
    lines.extend(["}};", "} // namespace lvrs::figma_colors", ""])
    return "\n".join(lines)


def qml_accents(tokens):
    lines = ["    // BEGIN FIGMA ACCENT TOKENS",
             "    // Generated from resources/figma-color-tokens.json; do not derive states from surfaces.",
             "    readonly property var figmaAccentRoles: ({"]
    for color in COLORS:
        lines.append(f'        "{color.lower()}": {{')
        for role in ROLES:
            lines.append(f'            "{role.lower()}": [{values(tokens[f"Accent/{color}/{role}"])}],')
        lines.append("        },")
    lines.extend(["    })", "    readonly property var figmaIconAccentRoles: ({"])
    for color in COLORS:
        lines.append(f'        "{color.lower()}": {{')
        for role in ROLES:
            name = f"Icon/Accent/{color}/{role}/Darker"
            if name in tokens:
                lines.append(f'            "{role.lower()}": [{values(tokens[name])}],')
        lines.append("        },")
    lines.extend(["    })", "    function accentRoleColor(colorName, roleName) {",
                  '        const palette = figmaAccentRoles[String(colorName || "").toLowerCase()]',
                  '        const channels = palette === undefined ? undefined : palette[String(roleName || "Default").toLowerCase()]',
                  "        return channels === undefined ? undefined : Qt.rgba(channels[0], channels[1], channels[2], channels[3])",
                  "    }", "    function iconAccentRoleColor(colorName, sourceRole) {",
                  '        const role = String(sourceRole || "Default").toLowerCase()',
                  '        if (role === "default") return accentRoleColor(colorName, "Hover")',
                  '        if (role === "hover") return accentRoleColor(colorName, "Pressed")',
                  '        const palette = figmaIconAccentRoles[String(colorName || "").toLowerCase()]',
                  '        const channels = palette === undefined ? undefined : palette[role]',
                  '        if (channels !== undefined) return Qt.rgba(channels[0], channels[1], channels[2], channels[3])',
                  "        const c = accentRoleColor(colorName, sourceRole)",
                  "        return c === undefined ? undefined : Qt.rgba(c.r * 0.9, c.g * 0.9, c.b * 0.9, c.a)",
                  "    }", "    // END FIGMA ACCENT TOKENS"])
    return "\n".join(lines)


def qml_backgrounds(tokens):
    lines = ["    // BEGIN FIGMA BACKGROUND TOKENS",
             "    // Generated from resources/figma-color-tokens.json."]
    for name, prop in BACKGROUNDS:
        if prop:
            lines.append(f"    readonly property color {prop}: Qt.rgba({values(tokens[name])})")
    extras = (("Glass/Fill", "alertGlassTint"), ("Surface/Dense/Fill", "materialDenseFill"),
              ("Surface/Glass/Fill", "materialGlassFill"), ("Backdrop/Base", "materialBackdropBase"),
              ("Alert/canvas", "alertCanvas"), ("Alert/surface", "alertSurface"))
    for name, prop in extras:
        lines.append(f"    readonly property color {prop}: Qt.rgba({values(tokens[name])})")
    lines.append("    // END FIGMA BACKGROUND TOKENS")
    return "\n".join(lines)


def replace_section(text, begin, end, replacement):
    start, stop = text.find(begin), text.find(end)
    if start < 0 or stop < start or text.find(begin, start + 1) >= 0:
        raise ValueError(f"Missing or duplicate generated section: {begin}")
    return text[:start] + replacement + text[stop + len(end):]


def qml_theme(tokens, source):
    source = replace_section(source, "    // BEGIN FIGMA ACCENT TOKENS",
                             "    // END FIGMA ACCENT TOKENS", qml_accents(tokens))
    source = replace_section(source, "    // BEGIN FIGMA BACKGROUND TOKENS",
                             "    // END FIGMA BACKGROUND TOKENS", qml_backgrounds(tokens))
    palette = {"accentBlue": "Accent/Blue/Default", "accentRed": "Accent/Red/Default",
               "accentGreen": "Accent/Green/Default", "accentYellow": "Accent/Yellow/Default",
               "accentPurple": "Accent/Purple/Default", "accentRose": "Accent/Rose/Default",
               "accentOrangeMuted": "Accent/Orange/Default", "accentBrownMuted": "Accent/Brown/Default",
               "accentLightCyan": "Accent/Cyan/Default", "accentDimTeal": "Accent/Teal/Default",
               "accentBlueMuted": "Accent/Blue/Selected",
               "accentBaseSkyVivid": "Accent/Blue/Default"}
    for name, token in palette.items():
        value = tokens[token]
        color = "#" + "".join(f"{round(value[k] * 255):02X}" for k in ("r", "g", "b"))
        expression = r'(\{ name: "' + re.escape(name) + r'", color: ")[^"]+(" \})'
        source, count = re.subn(expression, lambda m: m[1] + color + m[2], source)
        if count != 1:
            raise ValueError(f"Expected one extracted palette entry: {name}")
    return source


def window_noise_defaults(tokens, source):
    section = "\n".join([
        "    // BEGIN FIGMA WINDOW NOISE DEFAULTS",
        f'    QColor m_color = QColor::fromRgbF({values(tokens["Panel/window"])});',
        f'    QColor m_primaryColor = QColor::fromRgbF({values(tokens["Accent/Blue/Default"])});',
        "    // END FIGMA WINDOW NOISE DEFAULTS",
    ])
    return replace_section(source, "    // BEGIN FIGMA WINDOW NOISE DEFAULTS",
                           "    // END FIGMA WINDOW NOISE DEFAULTS", section)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="verify generated files without writing")
    args = parser.parse_args()
    tokens = load_tokens()
    outputs = {NATIVE: native_header(tokens), QML: qml_theme(tokens, QML.read_text()),
               NOISE: window_noise_defaults(tokens, NOISE.read_text())}
    changed = [path for path, content in outputs.items() if not path.exists() or path.read_text() != content]
    if args.check:
        if changed:
            print("Out-of-date Figma token outputs: " + ", ".join(str(p.relative_to(ROOT)) for p in changed), file=sys.stderr)
            return 1
    else:
        try:
            import ii_file_provider as provider
        except ModuleNotFoundError:
            installed = Path.home() / ".local/SDK/iiFileProvider/share/iiFileProvider/python"
            sys.path.insert(0, str(installed))
            import ii_file_provider as provider
        for path in changed:
            provider.write_text(path, outputs[path])
    print(f"Figma token outputs {'verified' if args.check else 'updated'}: {len(outputs)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
